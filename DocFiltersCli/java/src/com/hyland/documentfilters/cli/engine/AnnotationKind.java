package com.hyland.documentfilters.cli.engine;

/**
 * The kind of one annotation. The values are the {@code IGR_ANNOTATION_*}
 * constants, so the ordinal is the value.
 *
 * <p>Three members are renamed from the constants, as every binding renames them:
 * {@code RECTANGLE} is {@code IGR_ANNOTATION_SQUARE}, {@code ELLIPSE} is
 * {@code IGR_ANNOTATION_CIRCLE}, and {@code SQUIGGLY} is
 * {@code IGR_ANNOTATION_SQUIGGLE}. The full table is declared so that a widget or a
 * watermark annotation reports its real kind.
 */
public enum AnnotationKind
{
	UNKNOWN,
	TEXT,
	LINK,
	FREETEXT,
	LINE,
	RECTANGLE,
	ELLIPSE,
	POLYGON,
	POLYLINE,
	HIGHLIGHT,
	UNDERLINE,
	SQUIGGLY,
	STRIKEOUT,
	STAMP,
	CARET,
	INK,
	POPUP,
	FILE_ATTACHMENT,
	SOUND,
	MOVIE,
	WIDGET,
	SCREEN,
	PRINTERMARK,
	TRAPNET,
	WATERMARK,
	THREE_D,
	BARCODE,
	NAMED_DESTINATION
}
