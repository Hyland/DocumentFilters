package com.hyland.documentfilters.cli.engine;

/**
 * One node's kind in a page's element tree, as the structure report names them.
 * The values are the {@code IGR_PAGE_ELEMENT_TYPE_*} constants.
 */
public enum PageElementType
{
	PAGE(1),
	SECTION(2),
	COLUMN(3),
	PARAGRAPH(4),
	LINE(5),
	RUN(6),
	WORD(7),
	HEADER(8),
	FOOTER(9),
	IMAGE(10),
	TABLE(11),
	TABLE_ROW(12),
	TABLE_CELL(13),
	FORM(14),
	FORM_ELEMENT(15),
	FLOAT(16),
	GRAPHIC(17),
	TEXT_BOX(18),
	NOTES(19);

	private final int _value;

	PageElementType(int value)
	{
		_value = value;
	}

	public int getValue()
	{
		return _value;
	}
}
