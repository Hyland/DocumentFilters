package com.hyland.documentfilters.cli.engine;

/**
 * The kind of one interactive form field.
 *
 * <p>The member names are the {@code IGR_PAGE_FORM_ELEMENT_TYPE_*} constants' own
 * suffixes, because the constants are the one naming every port can derive
 * identically. The values are the constants', so the ordinal is the value.
 */
public enum FormElementType
{
	BUTTON,
	RADIOBUTTON,
	CHECKBOX,
	FILESELECT,
	MULTILINE_TEXT,
	SINGLELINE_TEXT,
	COMBOBOX,
	LISTBOX,
	SIGNATURE,
	PASSWORD
}
